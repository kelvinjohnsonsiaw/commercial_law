   "<b>Receivership:</b> a receiver is appointed by a secured creditor to realise the charged assets. The receiver's primary duty is to the debenture holder who appointed him, not the company (Shamji v Johnson Matthey; Downsview). Medforth v Blake held that a receiver who manages a business must take reasonable care to obtain the best price. Cuckmere Brick v Mutual Finance and Standard Chartered v Walker apply duties of care when selling charged property. Gomba Holdings v Homan and Yorkshire Bank v Hall deal with mortgagees' accounting duties.",
